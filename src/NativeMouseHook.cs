using System;
using System.Collections.Concurrent;
using System.ComponentModel;
using System.Runtime.InteropServices;

namespace WheelFix
{
    internal sealed class NativeMouseHook : IDisposable
    {
        private const int WhMouseLl = 14;
        private const int WmMouseWheel = 0x020A;
        private const uint LlmhfInjected = 0x00000001;

        private readonly WheelFilterCore _filter;
        private readonly NativeMethods.LowLevelMouseProc _callback;
        private readonly ConcurrentQueue<WheelTraceEvent> _traceEvents;
        private IntPtr _hookHandle;

        public NativeMouseHook(WheelFilterCore filter)
        {
            if (filter == null)
            {
                throw new ArgumentNullException("filter");
            }

            _filter = filter;
            _callback = HookCallback;
            _traceEvents = new ConcurrentQueue<WheelTraceEvent>();
            _hookHandle = IntPtr.Zero;
        }

        public bool TryDequeueTrace(out WheelTraceEvent traceEvent)
        {
            return _traceEvents.TryDequeue(out traceEvent);
        }

        public void Start()
        {
            if (_hookHandle != IntPtr.Zero)
            {
                return;
            }

            IntPtr moduleHandle = NativeMethods.GetModuleHandle(null);
            _hookHandle = NativeMethods.SetWindowsHookEx(
                WhMouseLl, _callback, moduleHandle, 0U);

            if (_hookHandle == IntPtr.Zero)
            {
                throw new Win32Exception(Marshal.GetLastWin32Error(),
                    L.Text(
                        "Windows rejected the global mouse hook.",
                        "Windows non ha accettato l'hook globale del mouse."));
            }
        }

        public void Dispose()
        {
            if (_hookHandle != IntPtr.Zero)
            {
                NativeMethods.UnhookWindowsHookEx(_hookHandle);
                _hookHandle = IntPtr.Zero;
            }

            GC.SuppressFinalize(this);
        }

        private IntPtr HookCallback(int nCode, IntPtr wParam, IntPtr lParam)
        {
            if (nCode >= 0 && wParam.ToInt32() == WmMouseWheel)
            {
                NativeMethods.MsLlHookStruct data =
                    (NativeMethods.MsLlHookStruct)Marshal.PtrToStructure(
                        lParam, typeof(NativeMethods.MsLlHookStruct));

                // Do not modify events generated by accessibility software,
                // remote-control tools or other applications.
                if ((data.Flags & LlmhfInjected) == 0U)
                {
                    int delta = unchecked((short)(data.MouseData >> 16));
                    WheelFilterDecision decision =
                        _filter.Process(delta, data.Time);
                    _traceEvents.Enqueue(new WheelTraceEvent(
                        data.Time, delta, decision));

                    if (decision == WheelFilterDecision.Block)
                    {
                        return new IntPtr(1);
                    }
                }
            }

            return NativeMethods.CallNextHookEx(_hookHandle, nCode, wParam, lParam);
        }
    }

    internal struct WheelTraceEvent
    {
        internal readonly uint Timestamp;
        internal readonly int Delta;
        internal readonly WheelFilterDecision Decision;

        internal WheelTraceEvent(
            uint timestamp,
            int delta,
            WheelFilterDecision decision)
        {
            Timestamp = timestamp;
            Delta = delta;
            Decision = decision;
        }
    }

    internal static class NativeMethods
    {
        internal delegate IntPtr LowLevelMouseProc(
            int nCode, IntPtr wParam, IntPtr lParam);

        [StructLayout(LayoutKind.Sequential)]
        internal struct Point
        {
            internal int X;
            internal int Y;
        }

        [StructLayout(LayoutKind.Sequential)]
        internal struct MsLlHookStruct
        {
            internal Point Pt;
            internal uint MouseData;
            internal uint Flags;
            internal uint Time;
            internal UIntPtr ExtraInfo;
        }

        [DllImport("user32.dll", SetLastError = true)]
        internal static extern IntPtr SetWindowsHookEx(
            int idHook,
            LowLevelMouseProc callback,
            IntPtr moduleHandle,
            uint threadId);

        [DllImport("user32.dll", SetLastError = true)]
        [return: MarshalAs(UnmanagedType.Bool)]
        internal static extern bool UnhookWindowsHookEx(IntPtr hookHandle);

        [DllImport("user32.dll")]
        internal static extern IntPtr CallNextHookEx(
            IntPtr hookHandle,
            int nCode,
            IntPtr wParam,
            IntPtr lParam);

        [DllImport("kernel32.dll", CharSet = CharSet.Unicode, SetLastError = true)]
        internal static extern IntPtr GetModuleHandle(string moduleName);

    }
}
